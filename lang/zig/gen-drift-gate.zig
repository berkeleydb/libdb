//! Emit a C program from the binding's frozen constant list (`consts.all`).
//! The generated program `#include <db.h>` and, for every row, `#if NAME !=
//! VALUE` / `#error`. If any constant the binding bakes in disagrees with the
//! installed header, the C compiler fails -- that is the drift gate's teeth.
//!
//! Usage: `gen-drift-gate <out.c>`. Run by `zig build drift`, which then
//! compiles the output against db.h and runs it (it prints OK and exits 0).
//! Pinned to Zig 0.16: `main` takes `std.process.Init.Minimal`, args via the
//! `Args.Iterator`, and the unmanaged `std.ArrayList(u8)` (`.empty` +
//! `print(gpa, ...)`).
const std = @import("std");
const consts = @import("consts.zig");

pub fn main(init: std.process.Init.Minimal) !void {
    var arena = std.heap.ArenaAllocator.init(std.heap.page_allocator);
    defer arena.deinit();
    const a = arena.allocator();

    var it = std.process.Args.Iterator.init(init.args);
    _ = it.skip(); // argv[0]
    const path = it.next() orelse {
        std.debug.print("usage: gen-drift-gate <out.c>\n", .{});
        std.process.exit(2);
    };

    var buf: std.ArrayList(u8) = .empty;
    try buf.appendSlice(a,
        \\/* GENERATED by gen-drift-gate.zig from consts.zig -- do not edit.
        \\ * The drift gate: a C11 _Static_assert per constant the Zig binding
        \\ * bakes in; the compiler fails if any disagrees with the installed
        \\ * db.h. _Static_assert (not #if) is used because the DBTYPE values are
        \\ * enum constants, invisible to the preprocessor. */
        \\#include <db.h>
        \\#include <stdio.h>
        \\
    );
    for (consts.all) |e| {
        try buf.print(a,
            "_Static_assert(({s}) == ({d}), \"drift: {s} != {d} in db.h\");\n",
            .{ e.name, e.value, e.name, e.value },
        );
    }
    try buf.print(a,
        \\int main(void) {{ printf("drift gate OK: {d} constants match db.h\n"); return 0; }}
        \\
    , .{consts.all.len});

    // std.fs reorganised in Zig 0.16 (createFileAbsolute removed); write via
    // libc, the same stable-ABI escape hatch the tests use for mkdir.
    const path_z = try a.dupeZ(u8, path);
    const fd = std.c.open(path_z, .{ .ACCMODE = .WRONLY, .CREAT = true, .TRUNC = true }, @as(std.c.mode_t, 0o644));
    if (fd < 0) return error.OpenFailed;
    defer _ = std.c.close(fd);
    var written: usize = 0;
    while (written < buf.items.len) {
        const n = std.c.write(fd, buf.items.ptr + written, buf.items.len - written);
        if (n <= 0) return error.WriteFailed;
        written += @intCast(n);
    }
}
